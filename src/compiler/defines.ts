import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

type DefineValueType =
  | { kind: "number" | "string" | "boolean" }
  | { kind: "array"; element: DefineValueType }
  | { kind: "union"; variants: DefineValueType[] };
interface DefineSchema {
  roots: Record<string, Record<string, Record<string, DefineValueType>>>;
}
const schema = JSON.parse(
  readFileSync(fileURLToPath(new URL("../schema/hoi4-defines.json", import.meta.url)), "utf8"),
) as DefineSchema;
function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value) && !("_krg" in value);
}
function matches(value: unknown, type: DefineValueType): boolean {
  if (type.kind === "union") return type.variants.some((variant) => matches(value, variant));
  if (type.kind === "array")
    return Array.isArray(value) && value.every((item) => matches(item, type.element));
  return typeof value === type.kind && (typeof value !== "number" || Number.isFinite(value));
}
function lua(value: unknown): string {
  if (typeof value === "number" && Number.isFinite(value)) return String(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  if (Array.isArray(value)) return `{ ${value.map(lua).join(", ")} }`;
  if (typeof value !== "string")
    throw new Error(
      "Lua defines accept only finite numbers, strings, booleans, and static arrays.",
    );
  let encoded = '"';
  for (const character of value) {
    const code = character.codePointAt(0)!;
    if (code >= 0xd800 && code <= 0xdfff)
      throw new Error("Lua strings cannot contain unpaired UTF-16 surrogates.");
    if (character === '"' || character === "\\") encoded += "\\" + character;
    else if (code < 32 || code === 127) encoded += "\\" + String(code).padStart(3, "0");
    else encoded += character;
  }
  return encoded + '"';
}
/** Produce only assignments to known native define identifiers; never evaluate Lua. */
export function lowerDefines(overrides: unknown): string {
  if (!isRecord(overrides))
    throw new Error("Defines requires a static record of native define roots.");
  const lines = ["-- Generated by Krieg. Native define overrides; source code is never executed."];
  const identifier = /^[A-Za-z_][A-Za-z0-9_]*$/;
  for (const [root, namespaces] of Object.entries(overrides)) {
    const knownRoot = Object.hasOwn(schema.roots, root) ? schema.roots[root] : undefined;
    if (!identifier.test(root) || !knownRoot)
      throw new Error(`Unknown native define root '${root}'.`);
    if (!isRecord(namespaces))
      throw new Error(`Define root '${root}' requires a namespace record.`);
    for (const [namespace, entries] of Object.entries(namespaces)) {
      const knownNamespace = Object.hasOwn(knownRoot, namespace) ? knownRoot[namespace] : undefined;
      if (!identifier.test(namespace) || !knownNamespace)
        throw new Error(`Unknown native define namespace '${root}.${namespace}'.`);
      if (!isRecord(entries))
        throw new Error(`Define namespace '${namespace}' requires a field record.`);
      for (const [key, value] of Object.entries(entries)) {
        if (value === undefined) continue;
        const type = Object.hasOwn(knownNamespace, key) ? knownNamespace[key] : undefined;
        if (!identifier.test(key) || !type)
          throw new Error(`Unknown native define '${root}.${namespace}.${key}'.`);
        if (!matches(value, type))
          throw new Error(
            `Define '${root}.${namespace}.${key}' has an incompatible value type or a non-finite number.`,
          );
        lines.push(`${root}.${namespace}.${key} = ${lua(value)}`);
      }
    }
  }
  if (lines.length === 1)
    throw new Error("A defines file must contain at least one native override.");
  return lines.join("\n") + "\n";
}
