function resolve(symbol) {
  return symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
}
function pageFor(module, symbol) {
  if (
    module.key === "./hoi4" &&
    symbol.declarations?.some((node) => /\/defines\./.test(node.getSourceFile().fileName))
  )
    return "defines";
  if (
    module.key === "./hoi4" &&
    /(?:Scope(?:Base|ByName|Name)?|CountryEffects|StateEffects|CountryTriggers|StateTriggers)$/.test(
      symbol.name,
    )
  )
    return "scopes";
  if (
    module.key === "./hoi4" &&
    symbol.declarations?.some((node) =>
      /\/(?:domains|definitions)\./.test(node.getSourceFile().fileName),
    )
  )
    return `domains/${slug(symbol.name.replace(/Spec$/, ""))}`;
  return module.file;
}
