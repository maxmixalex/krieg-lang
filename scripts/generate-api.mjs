import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import prettier from "prettier";
import { Application, Comment, Converter, ReflectionKind, makeRecursiveVisitor } from "typedoc";
import { MarkdownPageEvent, MarkdownRendererEvent } from "typedoc-plugin-markdown";
import { generateGameCatalogs } from "./generate-api-catalogs.mjs";
import { generateTaskReference, generateTaskNavigation } from "./generate-api-reference.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const packageJson = JSON.parse(read("package.json"));
const check = process.argv.includes("--check");
const generated = new Map();
const header =
  "<!-- Generated by TypeDoc and scripts/generate-api.mjs; edit declarations/JSDoc or scripts/api-topics.mjs / scripts/api-guide.md, then run npm run docs:api. -->\n\n";
const slug = (name) => name.toLowerCase().replace(/[^a-z0-9_-]+/g, "-");
const rawPages = new Map();
const entryPoints = Object.entries(packageJson.exports)
  .filter(([, value]) => typeof value === "object" && value.types)
  .map(([key, value]) => ({
    key,
    name: key === "." ? packageJson.name : packageJson.name + key.slice(1),
    short: key === "." ? "root" : key.slice(2),
    source: value.types.replace(/^\.\/dist\//, "src/").replace(/\.d\.ts$/, ".ts"),
  }));
for (const entry of entryPoints)
  if (!fs.existsSync(path.join(root, entry.source)))
    throw new Error(`Public entry point ${entry.name} has no TypeScript source: ${entry.source}`);

const manifest = {
  formatVersion: 3,
  packageVersion: packageJson.version,
  generator: {
    name: "TypeDoc",
    version: packageJson.devDependencies.typedoc,
    markdown: packageJson.devDependencies["typedoc-plugin-markdown"],
  },
  cwt: JSON.parse(read("src/schema/hoi4-schema.json")).provenance,
  modules: [],
  exports: [],
  commands: [],
};

// Render to an isolated directory, including in --check mode. Comparing every
// output also catches files that an older generator left behind.
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "krieg-api-"));
try {
  const app = await Application.bootstrapWithPlugins({
    options: path.join(root, "typedoc.json"),
    entryPoints: entryPoints.map((entry) => path.join(root, entry.source)),
    out: temporary,
  });

  // TypeDoc's own @inlineType mechanism expands small anonymous CWT shapes in
  // their owning field. Larger shared structures stay linked and are rendered
  // once by typedoc-plugin-missing-exports, avoiding exponential duplication.
  app.converter.on(Converter.EVENT_BEGIN, (context) => {
    for (const program of context.programs) {
      const source = program.getSourceFile(path.join(root, "src/sdk/domains.ts"));
      for (const node of source?.statements ?? [])
        if (
          ts.isInterfaceDeclaration(node) &&
          /^NativeShape\d+$/.test(node.name.text) &&
          node.members.length <= 8
        )
          context.inlineType.add(node.name.text);
    }
  });
  const project = await app.convert();
  if (!project || app.logger.hasErrors()) throw new Error("TypeDoc conversion failed");
  const modules = project.children.map((module) => {
    const entry = entryPoints.find(
      (item) => path.join(root, item.source) === module.sources?.[0]?.fullFileName,
    );
    if (!entry) throw new Error(`Unexpected TypeDoc entry point: ${module.name}`);
    module.name = entry.short;
    return { module, entry };
  });
  nameFieldTypes(project, modules);
  app.validate(project);
  if (app.logger.hasErrors() || app.logger.hasWarnings())
    throw new Error("TypeDoc validation emitted warnings or errors");

  // Defines has thousands of keys. TypeDoc's list renderer gives each key a
  // heading, so Zensical can index bounded sections rather than one huge table.
  app.renderer.on(MarkdownPageEvent.BEGIN, (event) => {
    app.options.setValue(
      "interfacePropertiesFormat",
      event.model.name === "DefineOverrides" ? "list" : "table",
    );
  });
  app.renderer.on(MarkdownPageEvent.END, (event) => {
    const source = event.model.sources?.[0]?.fullFileName;
    const old = `reference/${event.url}`;
    rawPages.set(old, {
      old,
      name: event.model.name,
      kind: event.model.kind,
      source: source ? path.relative(root, source).replaceAll(path.sep, "/") : undefined,
      content: event.contents,
    });
  });

  app.renderer.on(MarkdownRendererEvent.BEGIN, () => {
    const router = app.renderer.router;
    for (const { module, entry } of modules) {
      manifest.modules.push({ ...entry, page: `reference/${router.getFullUrl(module)}` });
      for (const exported of module.children ?? []) {
        if (exported.name === "field-types") continue;
        const target = exported.kindOf(ReflectionKind.Reference)
          ? exported.getTargetReflectionDeep()
          : exported;
        const source = target.sources?.[0]?.fullFileName;
        manifest.exports.push({
          module: entry.name,
          name: exported.name,
          page: `reference/${router.getFullUrl(target)}`,
          source: source ? path.relative(root, source).replaceAll(path.sep, "/") : entry.source,
        });
      }
    }
  });
  await app.generateOutputs(project);
  if (app.logger.hasErrors() || app.logger.hasWarnings())
    throw new Error("TypeDoc Markdown rendering emitted warnings or errors");
  manifest.modules.sort((a, b) => a.name.localeCompare(b.name, "en"));
  manifest.exports.sort((a, b) =>
    `${a.module}:${a.name}`.localeCompare(`${b.module}:${b.name}`, "en"),
  );
  generateGameCatalogs({ root, packageJson, manifest, generated, header });
  const reference = generateTaskReference({ root, generated, manifest, rawPages, header });
  generated.set(
    "zensical.toml",
    generateTaskNavigation({ source: read("zensical.toml"), groups: reference.groups }),
  );
  generateEntryPages();
  for (const [file, content] of generated) {
    if (
      file.startsWith("docs/api/") &&
      file.endsWith(".md") &&
      !file.startsWith("docs/api/reference/")
    ) {
      const page = file.slice("docs/api/".length);
      generated.set(file, reference.rewrite(content, page, page));
    }
  }
  generated.set("docs/api/manifest.json", JSON.stringify(manifest, null, 2));

  const options = JSON.parse(read(".prettierrc.json"));
  const failures = [];
  const staging = path.join(temporary, "assembled-api");
  for (const [file, source] of generated) {
    const content =
      file.endsWith(".toml") ||
      file.startsWith("docs/api/reference/") ||
      file === "docs/api/redirects.json"
        ? source
        : await prettier.format(source, { ...options, filepath: file });
    const absolute = path.join(root, file);
    if (check) {
      if (!fs.existsSync(absolute) || fs.readFileSync(absolute, "utf8") !== content)
        failures.push(file);
    } else {
      const destination = file.startsWith("docs/api/")
        ? path.join(staging, file.slice("docs/api/".length))
        : absolute;
      fs.mkdirSync(path.dirname(destination), { recursive: true });
      fs.writeFileSync(destination, content);
    }
  }
  if (check) {
    for (const absolute of filesUnder(path.join(root, "docs/api"))) {
      const file = path.relative(root, absolute).replaceAll(path.sep, "/");
      if (/\.(md|json)$/.test(file) && !generated.has(file)) failures.push(`${file} (obsolete)`);
    }
  } else {
    // Replace the directory as a unit so removed pages cannot survive a partial
    // write or an overlay filesystem's per-file deletion behavior.
    const destination = path.join(root, "docs/api");
    const previous = path.join(temporary, "previous-api");
    if (fs.existsSync(destination)) fs.renameSync(destination, previous);
    fs.renameSync(staging, destination);
  }
  if (failures.length)
    throw new Error(`API reference is stale. Run npm run docs:api.\n${failures.join("\n")}`);
  console.log(
    `${check ? "Checked" : "Generated"} ${generated.size} API files with TypeDoc; ${manifest.exports.length} public export records; ${manifest.commands.length} CWT commands.`,
  );
} finally {
  fs.rmSync(temporary, { recursive: true, force: true });
}

function filesUnder(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs
    .readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) =>
      entry.isDirectory()
        ? filesUnder(path.join(directory, entry.name))
        : [path.join(directory, entry.name)],
    )
    .sort();
}

/** Keep shared field structures navigable without publishing implementation IDs. */
function nameFieldTypes(project, modules) {
  const queue = modules.flatMap(({ module }) =>
    (module.children ?? [])
      .filter((item) => item.name !== "field-types" && !item.kindOf(ReflectionKind.Reference))
      .map((item) => ({ item, label: item.name })),
  );
  queue.sort((a, b) => a.label.length - b.label.length || a.label.localeCompare(b.label, "en"));
  const visited = new Set();
  const renames = new Map();
  function scan(item, label) {
    if (visited.has(item)) return;
    visited.add(item);
    const visitor = makeRecursiveVisitor({
      reference(type) {
        const target = type.reflection;
        if (!target || target.parent?.name !== "field-types") return;
        if (/^NativeShape\d+$/.test(target.name)) {
          if (!renames.has(target)) renames.set(target, label);
          queue.push({ item: target, label: renames.get(target) });
        } else queue.push({ item: target, label });
      },
      reflection(type) {
        scan(type.declaration, label);
      },
    });
    item.type?.visit(visitor);
    for (const type of item.extendedTypes ?? []) type.visit(visitor);
    for (const child of [
      ...(item.children ?? []),
      ...(item.signatures ?? []),
      ...(item.indexSignatures ?? []),
      ...(item.parameters ?? []),
      ...(item.typeParameters ?? []),
    ])
      scan(
        child,
        child.name === "__type" || child.kindOf(ReflectionKind.CallSignature)
          ? label
          : `${label}.${child.name}`,
      );
  }
  for (let index = 0; index < queue.length; index++) scan(queue[index].item, queue[index].label);
  for (const [item, label] of renames) {
    item.name = `${label} fields`;
    item.comment ??= new Comment();
    item.comment.summary.unshift({
      kind: "text",
      text: `\`${label}\` 引用的共享字段结构。该标题是字段路径，不是可导入的包导出；请从对应的公开 Spec 填写对象。\n\n`,
    });
  }
  const visitor = makeRecursiveVisitor({
    reference(type) {
      if (renames.has(type.reflection)) type.name = type.reflection.name;
    },
  });
  for (const item of Object.values(project.reflections)) {
    item.type?.visit(visitor);
    for (const type of item.extendedTypes ?? []) type.visit(visitor);
  }
  const unnamed = Object.values(project.reflections).filter(
    (item) => item.parent?.name === "field-types" && /^NativeShape\d+$/.test(item.name),
  );
  if (unnamed.length)
    throw new Error(`Unreachable generated field types: ${unnamed.map((x) => x.name).join(", ")}`);
}

function generateEntryPages() {
  const link = (entry, from = "") =>
    path.posix.relative(from || ".", entry.page.split("#")[0]) +
    (entry.page.includes("#") ? `#${entry.page.split("#")[1]}` : "");
  const pages = new Map();
  for (const entry of manifest.exports) {
    const module = manifest.modules.find((item) => item.name === entry.module);
    let page = module.short.replaceAll("/", "-");
    if (entry.module === "krieg-lang/hoi4") {
      if (entry.source === "src/sdk/defines.ts") page = "defines";
      else if (
        /(?:Scope(?:Base|ByName|Name)?|CountryEffects|StateEffects|CountryTriggers|StateTriggers)$/.test(
          entry.name,
        )
      )
        page = "scopes";
      else if (entry.source === "src/sdk/domains.ts")
        page = `domains/${slug(entry.name.replace(/Spec$/, ""))}`;
    }
    const entries = pages.get(page) ?? [];
    entries.push(entry);
    pages.set(page, entries);
  }
  const titles = {
    root: "Node.js 工具入口",
    hoi4: "HOI4 玩法 API",
    scopes: "作用域、效果与条件",
    defines: "Lua Defines",
    ui: "UI 与 TSX",
    "ui-jsx-runtime": "JSX 类型入口",
    compiler: "编译器 API",
    project: "项目 API",
    pdx: "有序 PDX API",
    eslint: "ESLint API",
  };
  for (const [page, entries] of pages) {
    const base = page.includes("/") ? "../" : "";
    const lines = [
      header,
      `# ${titles[page] ?? entries[0].name.replace(/Spec$/, "")}`,
      "",
      `[按任务查找 API](${base}index.md) · [公开入口与全部符号](${base}reference/index.md)`,
      "",
      "相关函数、配置和句柄按任务放在同一页；点击符号直达其章节。TypeDoc 生成完整参数、字段、继承关系与源码链接。",
      "",
      "| 公开符号 | 详细参考 |",
      "| --- | --- |",
      ...entries.map(
        (entry) =>
          `| <a id="${slug(entry.name)}"></a> \`${entry.name}\` | [查看 ${entry.name}](${link(entry, path.posix.dirname(page))}) |`,
      ),
      "",
    ];
    if (page === "defines")
      lines.push("[按 Lua 根与命名空间查询全部键](defines/namespaces.md)", "");
    if (page === "scopes")
      lines.push(
        "[按原生命令名查找效果与条件](commands/index.md) · [作用域指南](../guide/scopes.md)",
        "",
      );
    if (page === "hoi4")
      lines.push("[常用玩法写法](../guide/focuses.md) · [原生内容领域目录](domains.md)", "");
    if (page === "ui") lines.push("[组件、布局与游戏行为](../guide/ui.md)", "");
    generated.set(`docs/api/${page}.md`, lines.join("\n"));
  }
  const guide = read("scripts/api-guide.md");
  generated.set("docs/api/index.md", header + guide.replaceAll("{{version}}", packageJson.version));
}
